import { defineConfig } from 'vite'
import vue from '@vitejs/plugin-vue'

/**
 * Vite — сборщик фронтенда (аналог Maven для бэкенда).
 *
 * ГЛАВНОЕ: server.proxy — это мост между фронтом и бэкендом.
 *
 * Как это работает (твой вопрос «как соединить»):
 *  - бэкенд живёт на http://localhost:8080;
 *  - фронт (Vite) живёт на http://localhost:5173;
 *  - браузер НЕ может просто так обращаться с 5173 на 8080
 *    (политика CORS заблокирует — разные порты = разные «сайты»);
 *  - поэтому Vite-сервер «проксирует»: когда фронт шлёт запрос
 *    на /api/... на свой же порт 5173, Vite ЗА НАС пересылает его
 *    на localhost:8080 и возвращает ответ обратно.
 *
 * Итог: в коде фронта мы пишем просто fetch('/api/halls'),
 * а Vite сам достучится до бэкенда. На проде (собранная версия)
 * фронт и бэкенд обычно живут на одном домене, и прокси не нужен.
 *
 * ([дальше в чате покажу, как проверить на живом примере])
 */
export default defineConfig({
  plugins: [vue()],
  server: {
    port: 5173,
    host: true, // разрешаем доступ с телефона в локальной сети (--host)
    proxy: {
      '/api': {
        target: 'http://localhost:8080', // куда слать запросы с /api
        changeOrigin: true,
      },
      '/h2-console': {
        target: 'http://localhost:8080',
        changeOrigin: true,
      },
    },
  },
})