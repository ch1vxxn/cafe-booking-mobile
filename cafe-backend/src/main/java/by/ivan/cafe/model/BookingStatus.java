package by.ivan.cafe.model;

/**
 * Статусы брони — «жизненный цикл» бронирования.
 *
 * Бронь НЕ удаляется из базы, а проходит по статусам — так админ
 * всегда видит полную историю и может понять, что происходит.
 *
 * Жизненный цикл (клиентский путь):
 *
 *   NEW  ──(админ позвонил, гость подтвердил)──▶ CONFIRMED
 *   NEW/CONFIRMED ──(гость передумал)──▶ CANCELLED
 *   CONFIRMED ──(гость пришёл)──▶ COMPLETED
 *   CONFIRMED ──(гость не пришёл)──▶ NO_SHOW
 *
 * Почему NEW и CONFIRMED разные:
 * админисратор кафе по нашей модели звонит гостю. Пока он не
 * подтвердил — бронь "новая" (NEW). Подтвердил — CONFIRMED.
 * Это и есть «кафеский путь»: живой контроль, как в настоящем кафе.
 */
public enum BookingStatus {
    NEW,          // только что создана, ждёт подтверждения админом
    CONFIRMED,    // админ позвонил, гость подтвердил
    COMPLETED,    // гость пришёл, стол отработал
    CANCELLED,    // отменена (гостем или админом)
    NO_SHOW       // гость не пришёл
}