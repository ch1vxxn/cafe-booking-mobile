package by.ivan.cafe.model;

/**
 * Роли пользователей системы.
 *
 * enum — это тип данных, который может принимать ТОЛЬКО одно из
 * перечисленных значений. Так мы гарантируем, что у пользователя
 * не окажется опечатки вроде "admen" вместо "ADMIN".
 *
 * Что означают роли:
 *  - GUEST — обычный гость: бронирует столы, смотрит свои брони;
 *  - ADMIN — администратор кафе: видит ВСЕ брони, меняет их статусы,
 *            управляет залами и столами.
 *
 * Хранится в БД как строка 'GUEST' / 'ADMIN'.
 */
public enum Role {
    GUEST,
    ADMIN
}